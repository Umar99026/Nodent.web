import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const questionFiles = [
  "src/components/quiz/McqQuestion.tsx",
  "src/components/quiz/ShortQuestion.tsx",
  "src/components/quiz/LongQuestion.tsx",
];
const forbiddenRenderers = [
  "WrongAnswerFeedbackPanel",
  "AiMarkingFeedbackPanel",
  "AiMarkingPartFeedback",
  "MultipartMarkBreakdown",
  "MarkBreakdownFeedbackPanel",
];

const failures = [];

for (const relativePath of questionFiles) {
  const source = readFileSync(resolve(root, relativePath), "utf8");
  const unifiedRenders = source.match(/<QuestionFeedbackPanel\b/g)?.length ?? 0;
  if (unifiedRenders !== 1) {
    failures.push(
      `${relativePath} must render QuestionFeedbackPanel exactly once (found ${unifiedRenders}).`,
    );
  }
  for (const renderer of forbiddenRenderers) {
    if (source.includes(renderer)) {
      failures.push(`${relativePath} must not use legacy feedback renderer ${renderer}.`);
    }
  }
}

const panelSource = readFileSync(
  resolve(root, "src/components/quiz/QuestionFeedbackPanel.tsx"),
  "utf8",
);
if ((panelSource.match(/data-question-feedback=/g)?.length ?? 0) !== 1) {
  failures.push("QuestionFeedbackPanel must own the single data-question-feedback marker.");
}
if (!panelSource.includes(">\n              Feedback\n")) {
  failures.push('QuestionFeedbackPanel must keep the visible title "Feedback".');
}

const builderSource = readFileSync(resolve(root, "src/lib/wrongAnswerFeedback.ts"), "utf8");
for (const requiredPhrase of ["Correct answer:"]) {
  if (!builderSource.includes(requiredPhrase)) {
    failures.push(`Wrong-answer feedback must include the permanent "${requiredPhrase}" step.`);
  }
}
if (builderSource.includes("Worked steps are not available for this question yet.")) {
  failures.push("Wrong-answer feedback must never show a worked-steps-unavailable placeholder.");
}
const workedSolutionHookSource = readFileSync(
  resolve(root, "src/hooks/useWorkedSolution.ts"),
  "utf8",
);
if (!workedSolutionHookSource.includes("API_PATHS.written.solution")) {
  failures.push("Missing authored steps must be generated by the worked-solution API.");
}
if (!panelSource.includes("Generating the exact worked steps for this question")) {
  failures.push("Feedback must visibly load exact worked steps instead of showing a placeholder.");
}
const apiSource = readFileSync(resolve(root, "../functions/api/[[path]].ts"), "utf8");
if (!apiSource.includes('app.post("/api/written/:subjectId/:questionKey/solution"')) {
  failures.push("The authenticated worked-solution API route must remain available.");
}

const forbiddenGenericMethod =
  "Identify the required relationship, substitute the given values carefully";
if (builderSource.includes(forbiddenGenericMethod)) {
  failures.push("Wrong-answer feedback must not invent the generic calculation method.");
}

const quizPageSource = readFileSync(resolve(root, "src/pages/QuizPage.tsx"), "utf8");
if ((quizPageSource.match(/<AiResponseQuotaBar\b/g)?.length ?? 0) !== 1) {
  failures.push("QuizPage must render the shared AI response quota bar exactly once.");
}
const questionCardContentIndex = quizPageSource.indexOf("<CardContent");
const quotaBarIndex = quizPageSource.indexOf("<AiResponseQuotaBar");
const currentQuestionIndex = quizPageSource.indexOf("{currentGroup && subjectId", quotaBarIndex);
if (
  questionCardContentIndex < 0 ||
  quotaBarIndex < questionCardContentIndex ||
  currentQuestionIndex < quotaBarIndex
) {
  failures.push("The shared AI response quota bar must stay inside the question card.");
}
for (const hiddenModeLabel of [
  "Normal mode",
  "Breakdown mode",
  "Switch to mark breakdown mode",
]) {
  if (quizPageSource.includes(hiddenModeLabel)) {
    failures.push(`QuizPage must not expose the hidden ${hiddenModeLabel} control.`);
  }
}
const shortQuestionSource = readFileSync(
  resolve(root, "src/components/quiz/ShortQuestion.tsx"),
  "utf8",
);
if (shortQuestionSource.includes("<AiResponseQuotaBar")) {
  failures.push("ShortQuestion must not render a second question-specific quota bar.");
}
if (!shortQuestionSource.includes("notifyPremiumUsageUpdated()")) {
  failures.push("A successful detailed AI mark must refresh the shared quota bar.");
}
if (!shortQuestionSource.includes("requestShortAnswerAiMark")) {
  failures.push("Typed and drawn short answers must use the shared detailed AI marking path.");
}
if (shortQuestionSource.includes("if (!premium && aiResponsesLocked) {")) {
  failures.push("Exhausted AI quota must never block typed instant-matching submissions.");
}
if (!shortQuestionSource.includes("aiResponsesLocked && hasDrawn")) {
  failures.push("Only drawn submissions may be blocked when the free AI quota is exhausted.");
}
if (!shortQuestionSource.includes("Daily AI feedback used. Marking this typed answer with instant matching.")) {
  failures.push("A typed submission racing the quota refresh must fall back to instant matching.");
}
if (!apiSource.includes("USAGE_KIND_AI_RESPONSE")) {
  failures.push("Typed and drawn detailed feedback must share one backend usage bucket.");
}
if (apiSource.includes("Typed short answers use instant answer matching and do not need AI marking.")) {
  failures.push("The backend must not reject typed short answers from detailed AI marking.");
}
if (!apiSource.includes("if (!isPremiumAccount(user) && isShortType)")) {
  failures.push("Every successful free typed-or-drawn short-answer AI mark must consume quota.");
}

const mathNormalizerSource = readFileSync(
  resolve(root, "src/lib/questionMathText.ts"),
  "utf8",
);
const mathPipelineTestSource = readFileSync(
  resolve(root, "scripts/test-math-pipeline.ts"),
  "utf8",
);
if (!mathPipelineTestSource.includes(String.raw`Find \frac{d}{dx}\left\frac{x^{2}+1}{e^x}\right$$.`)) {
  failures.push("The malformed derivative delimiter case must remain covered by the math pipeline.");
}
if (!mathNormalizerSource.includes(String.raw`out = out.replace(/\\right(?=\s*\$)/g, "\\right)");`)) {
  failures.push("Question math normalization must repair missing right delimiters before KaTeX rendering.");
}

for (const relativePath of questionFiles) {
  const source = readFileSync(resolve(root, relativePath), "utf8");
  if (!source.includes("useWorkedSolution")) {
    failures.push(`${relativePath} must load an exact worked solution when authored steps are absent.`);
  }
}

const practiceQuestionSource = readFileSync(
  resolve(root, "src/lib/practiceQuestions.ts"),
  "utf8",
);
for (const requiredGuidancePath of [
  "options,\n      answer,\n      guidance,",
  "acceptedAnswers,\n      guidance,",
]) {
  if (!practiceQuestionSource.includes(requiredGuidancePath)) {
    failures.push("Question loading must preserve authored guidance for every question type.");
  }
}

if (failures.length) {
  throw new Error(`Feedback contract failed:\n- ${failures.join("\n- ")}`);
}

console.log("Feedback contract passed: one shared feedback box per question type.");
